import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = {};
async function collect(directory, prefix = '') {
  for (const item of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const relative = `${prefix}/${item.name}`;
    if (item.isDirectory()) await collect(path.join(directory, item.name), relative);
    else if (/\.(html|css|js)$/.test(item.name)) assets[relative] = await readFile(path.join(directory, item.name), 'utf8');
  }
}
await collect(path.join(root, 'public'));
const runtime = await readFile(path.join(root, 'scripts/handler.js'), 'utf8');
await mkdir(path.join(root, 'src'), { recursive: true });
await writeFile(path.join(root, 'src/index.js'), `// Generated by npm run build. Edit public/ to change website content.\nconst assets = ${JSON.stringify(assets)};\n${runtime}`, 'utf8');
console.log(`Built ${Object.keys(assets).length} assets into src/index.js`);
